export const locale = ref<Locale>(initialLocale())

export function setLocale(nextLocale: Locale) {
  locale.value = nextLocale
  try {
    localStorage.setItem(STORAGE_KEY, nextLocale)
  } catch {
    // Keep the in-memory language choice if storage is unavailable.
  }
}

export function t(key: keyof typeof en, params: Record<string, string | number> = {}) {
  let text = (locale.value === 'zh' ? zh : en)[key] ?? en[key] ?? key
  for (const [name, value] of Object.entries(params)) {
    text = text.replaceAll(`{${name}}`, String(value))
  }
  return text
}

function initialLocale(): Locale {
  try {
    const stored = localStorage.getItem(STORAGE_KEY)
    if (stored === 'zh' || stored === 'en') return stored
  } catch {
    // Ignore storage failures and fall back to browser language.
  }
  return navigator.language.toLowerCase().startsWith('zh') ? 'zh' : 'en'
}
